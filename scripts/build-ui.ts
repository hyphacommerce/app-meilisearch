// Bundles the settings page's script (src/ui/settings-client.ts, with @hyphacommerce/app-bridge)
// into a string module both hosts serve at /settings.js. The output is committed;
// `--check` fails while it's stale (CI runs it).

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const entry = fileURLToPath(new URL("../src/ui/settings-client.ts", import.meta.url));
const output = fileURLToPath(new URL("../src/ui/generated/settings-client.ts", import.meta.url));

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: "iife",
  minify: true,
  target: "es2022",
  platform: "browser",
  legalComments: "none",
  write: false,
});
const code = result.outputFiles[0]?.text ?? "";
const module = `// Generated by scripts/build-ui.ts from src/ui/settings-client.ts: don't edit.\nexport const SETTINGS_CLIENT_JS = ${JSON.stringify(code)};\n`;

if (process.argv.includes("--check")) {
  const current = await readFile(output, "utf8").catch(() => "");
  if (current !== module) {
    console.error("src/ui/generated/settings-client.ts is stale: run `pnpm ui:build`");
    process.exit(1);
  }
  console.log("the settings script is current");
} else {
  await writeFile(output, module);
  console.log(`wrote ${output} (${code.length} bytes)`);
}
